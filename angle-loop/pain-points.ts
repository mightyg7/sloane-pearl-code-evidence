function buildUserPrompt(
  args: GeneratePainPointsArgs,
  visualDescription: string,
  products: AboProductInput[],
): string {
  const blocks: string[] = [];
  if (args.brandName?.trim()) {
    blocks.push(`Brand: ${args.brandName.trim()} (reference at most once; NEVER name a premium/luxury brand).`);
  }
  if (products.length > 1) {
    for (let i = 0; i < products.length; i++) {
      blocks.push(`Product ${i + 1}: ${products[i].title}`);
      if (products[i].description?.trim()) {
        blocks.push("Description:", products[i].description!.trim().slice(0, 600));
      }
    }
  } else {
    blocks.push(`Product title: ${products[0].title}`);
    if (products[0].description?.trim()) {
      blocks.push("Description:", products[0].description!.trim().slice(0, 1500));
    }
  }
  if (args.collection?.trim()) blocks.push(`Collection: ${args.collection.trim()}`);
  if (visualDescription.trim()) {
    blocks.push(
      "",
      "VISIBLE-FEATURE NOTES (from the product photos — ground the mechanism and imagePrompt in these):",
      visualDescription.trim(),
    );
  }
  blocks.push("", "Output the JSON now.");
  return blocks.join("\n");
}

/**
 * Plain-vision pass: describe ONLY what is visibly true in the product photos.
 *
 * qcode reliably handles image + NO tools/JSON/prefill (plain vision), but
 * intermittently mangles image + JSON-in-prompt (empty body / preamble). So we
 * split: this call derives prose "visible-feature notes", and the pain-point
 * JSON is generated separately, TEXT-ONLY, grounded on those notes. Returns ""
 * on any failure so generation falls back to title/description grounding — a
 * weaker mechanism, but never a hard failure. See
 * reference_qcode-drops-tools-on-images.
 */
async function describeProductsVisually(
  anthropic: ReturnType<typeof createAnthropic>,
  products: AboProductInput[],
  collection: string | undefined,
): Promise<string> {
  const multi = products.length > 1;
  // Single product: up to 4 photos of that one garment (today's behavior).
  // Collection: ONE photo per product, labeled, so "image j" maps to
  // "Product n" unambiguously even when a product has no photo.
  const pairs = multi
    ? products
        .map((p, i) => ({ n: i + 1, title: p.title, url: p.imageUrls[0] }))
        .filter((x): x is { n: number; title: string; url: string } => !!x.url)
    : products[0].imageUrls.slice(0, 4).map((url) => ({ n: 1, title: products[0].title, url }));
  if (pairs.length === 0) return "";
  const imageBlocks = pairs.map((x) => ({
    type: "image" as const,
    source: { type: "url" as const, url: x.url },
  }));
  const prompt = multi
    ? [
        `These are product photos from the "${collection ?? "collection"}" collection: ` +
          pairs.map((x, j) => `image ${j + 1} = Product ${x.n} ("${x.title}")`).join(", ") +
          ".",
        'For EACH product, in 1-3 sentences describe ONLY what is visibly true about it — cut, material, sole, strap, neckline, drape, fit, thickness, finish, colour. Concrete features a shopper could verify from the photo. No marketing language, no invented internal features. Start each product\'s notes with "Product <n> (<title>):" on its own line. If a photo is unclear, say what you can and stop.',
      ].join("\n")
    : [
        `Look at these product photos of "${products[0].title}".`,
        "In 2-4 sentences, describe ONLY what is visibly true about the product — cut, material, sole, strap, neckline, drape, fit, thickness, finish, colour. Concrete features a shopper could verify from the photo. No marketing language, no invented internal features. If the photos are unclear, say what you can and stop.",
      ].join("\n");
  try {
    const res = await anthropic.messages.create({
      model: MODEL,
      max_tokens: multi ? 700 : 400,
      messages: [{ role: "user", content: [...imageBlocks, { type: "text" as const, text: prompt }] }],
    });
    await trackAnthropicUsage({ usage: res.usage, model: MODEL, purpose: "abo-pain-points-vision" });
    return res.content
      .filter((b): b is Anthropic.TextBlock => b.type === "text")
      .map((b) => b.text)
      .join("")
      .trim();
  } catch (e) {
    console.warn(
      "[abo:pain-points] vision describe failed, falling back to text-only grounding:",
      e instanceof Error ? e.message : e,
    );
    return "";
  }
}

export async function generatePainPoints(
  args: GeneratePainPointsArgs,
): Promise<PainPoint[]> {
  const apiKey = process.env.ANTHROPIC_API_KEY_ADS || process.env.ANTHROPIC_API_KEY;
  if (!apiKey) throw new Error("ANTHROPIC_API_KEY_ADS not set");
  const anthropic = createAnthropic({ apiKey, purpose: "abo-pain-points", ads: true });

  // Angle Loop: steer angles with the store's brief when one exists.
  // Fail-open — any error here yields the exact legacy prompt.
  let briefBlock = "";
  try {
    const brief = await getCurrentBrief(args.accountId);
    if (brief && (brief.weights.length > 0 || brief.avoid.length > 0)) {
      const explorationSlots = Math.max(1, Math.round(args.count * EXPLORATION_FLOOR));
      briefBlock = buildAngleBriefPromptBlock(brief, explorationSlots);
    }
  } catch (e) {
    console.warn("[angle-loop] brief injection skipped:", e instanceof Error ? e.message : e);
  }
  // Ground the pain points in the real product WITHOUT sending an image on the
  // JSON call: qcode intermittently mangles an image+JSON request (empty body /
  // preamble — observed live in ABO composed + overlay). So do a PLAIN-VISION
  // describe pass first (qcode's one reliable image mode), then generate the
  // JSON text-only from those notes. See reference_qcode-drops-tools-on-images.
  const products = normalizeProducts(args);
  const visualDescription = await describeProductsVisually(anthropic, products, args.collection);

  const system = buildSystemPrompt(args, briefBlock, products);
  const userText = buildUserPrompt(args, visualDescription, products);
  // TEXT-ONLY messages — no image block. The image+JSON combo is exactly what
  // qcode mangles; the visible-feature notes above carry the grounding instead.
  const messages: Anthropic.MessageParam[] = [{ role: "user", content: userText }];

  const loopStart = Date.now();
  let lastErr: unknown = null;
  let lastRaw = "";
  for (let attempt = 1; attempt <= MAX_ATTEMPTS; attempt++) {
    // Checked before starting attempt 2+ only — attempt 1 always runs
    // regardless of how long the (already-completed) brief lookup + vision
    // pass took, since `loopStart` is taken right here, not at function entry.
    if (attempt > 1) {
      const elapsedMs = Date.now() - loopStart;
      if (elapsedMs > RETRY_BUDGET_MS) {
        throw new Error(
          `pain-points: giving up after ${attempt - 1} attempts / ${Math.round(elapsedMs / 1000)}s ` +
            `(last: ${lastErr instanceof Error ? lastErr.message : lastErr}). Stopping before the retry ` +
            `loop itself blows the route's own time budget.`,
        );
      }
    }
    // The SDK call sits INSIDE the try: a transient network error, a rate
    // limit, or the upstream returning a malformed/empty response at the
    // HTTP layer must be retried exactly like a validation failure — that is
    // the actual failure the operator hit in production (a bare 502 with no
    // trace), and it used to bypass every attempt + all of the diagnostics
    // below by throwing before parsePainPoints ever ran.
    let raw = "";
    let stopReason: string | null = null;
    try {
      const res = await anthropic.messages.create({
        model: MODEL,
        max_tokens: JSON_MAX_TOKENS,
        system,
        messages,
      });
      await trackAnthropicUsage({ usage: res.usage, model: MODEL, purpose: "abo-pain-points" });
      raw = res.content.filter((b): b is Anthropic.TextBlock => b.type === "text").map((b) => b.text).join("").trim();
      lastRaw = raw;
      // Known upstream flake: the provider proxy in front of Anthropic
      // intermittently stops mid-output. stop_reason lets us tell that apart
      // from a genuine prompt/formatting bug instead of just reporting "N
      // chars of valid-looking JSON" and leaving it to guesswork.
      stopReason = res.stop_reason ?? null;
      return parsePainPoints(raw, args, products, stopReason);
    } catch (err) {
      lastErr = err;
      console.warn(
        `[abo:pain-points] attempt ${attempt}/${MAX_ATTEMPTS} failed (stop_reason=${stopReason ?? "unknown"}, raw length=${raw.length}):`,
        err instanceof Error ? err.message : err,
      );
      if (attempt === MAX_ATTEMPTS) break;
      // Only replay the previous turn when there IS a previous turn to
      // replay. An SDK-level throw (network error, rate limit, malformed
      // upstream response) never produced any assistant output, so `raw` is
      // still "" here — pushing an empty assistant message would poison the
      // conversation history for no reason; just retry the same request.
      if (raw) {
        messages.push({ role: "assistant", content: raw });
        messages.push({
          role: "user",
          content: `Your output failed validation: ${err instanceof Error ? err.message : String(err)}\n\nRe-emit the COMPLETE JSON object only — no preamble, no fences.`,
        });
      }
    }
  }
  throw new Error(
    `pain-points: generation failed after ${MAX_ATTEMPTS} attempts. Last: ${lastErr instanceof Error ? lastErr.message : lastErr}. Raw(120): ${lastRaw.slice(0, 120)}`,
  );
}

function parsePainPoints(
  raw: string,
  args: GeneratePainPointsArgs,
  products: AboProductInput[],
  stopReason?: string | null,
): PainPoint[] {
  const json = raw
    .replace(/^```json\s*/i, "")
    .replace(/^```\s*/i, "")
    .replace(/```\s*$/i, "")
    .trim();
  let parsed: { painPoints?: unknown };
  try {
    parsed = JSON.parse(json);
  } catch {
    // Twice on prod the model stopped mid-output (the provider proxy in
    // front of Anthropic is known to do this intermittently) and the error
    // read like a prompt bug because it showed only a clean-looking 120-char
    // excerpt. Naming stop_reason + the full raw length turns "non-JSON: {"
    // into an actionable "was this truncated, or genuinely malformed?".
    const truncationNote =
      stopReason === "max_tokens"
        ? " — response was TRUNCATED by the token limit (stop_reason=max_tokens)"
        : ` (stop_reason=${stopReason ?? "unknown"})`;
    throw new Error(
      `model returned non-JSON${truncationNote}, raw length ${raw.length}: ${raw.slice(0, 120)}`,
    );
  }
  const list = Array.isArray(parsed.painPoints) ? parsed.painPoints : [];
  // A short list is silently accepted downstream via slice(0, count) unless
  // we reject it here — and the count is the number of ad sets in the ABO
  // test, so under-delivering silently changes the operator's budget split.
  // Zero falls out of this same check (0 < count whenever count >= 1).
  if (list.length < args.count) {
    throw new Error(
      `model returned ${list.length} pain points, expected exactly ${args.count}`,
    );
  }

  const seen = new Set<string>();
  return list.slice(0, args.count).map((p: Record<string, any>, i: number) => {
    const label =
      typeof p?.label === "string" && p.label.trim() ? p.label.trim() : `Angle ${i + 1}`;
    let slug = slugify(label);
    while (seen.has(slug)) slug = `${slug}-${i}`;
    seen.add(slug);

    const buyer = typeof p?.buyer === "string" ? p.buyer.trim() : "";
    const painPoint = typeof p?.painPoint === "string" ? p.painPoint.trim() : label;
    const mechanism = typeof p?.mechanism === "string" ? p.mechanism.trim() : "";
    const onImageText = (typeof p?.onImageText === "string" && p.onImageText.trim()
      ? p.onImageText.trim()
      : label
    ).slice(0, 16);

    // Collection runs: the model picks the ONE product (1-based) that best
    // expresses this angle; store 0-based to match scrapedProducts order.
    // Out-of-range / missing picks and single-product runs stay untagged.
    const rawIdx = Number((p as Record<string, unknown>)?.product);
    const tagged =
      products.length > 1 && Number.isInteger(rawIdx) && rawIdx >= 1 && rawIdx <= products.length
        ? products[rawIdx - 1]
        : null;

    const promptHint =
      typeof p?.imagePrompt === "string" && p.imagePrompt.trim()
        ? p.imagePrompt.trim()
        : `Photorealistic product shot of ${(tagged ?? products[0]).title}, clean white background, no human faces, bold on-image text "${onImageText}".`;
    const imagePrompt = /square|1:1/i.test(promptHint)
      ? promptHint
      : `${promptHint} Square 1:1 composition.`;

    return {
      slug,
      label,
      buyer,
      painPoint,
      mechanism,
      onImageText,
      imagePrompt,
      ...(tagged
        ? {
            productIndex: rawIdx - 1,
            productTitle: tagged.title,
            productImageUrl: tagged.imageUrls[0],
          }
        : {}),
      copy: {
        primaryTexts: sizeAndClamp(p?.copy?.primaryTexts, args.creativesPerPainPoint, LIMIT.primary, "primary", painPoint || label),
        headlines: sizeAndClamp(p?.copy?.headlines, args.creativesPerPainPoint, LIMIT.headline, "headline", label),
        descriptions: sizeAndClamp(p?.copy?.descriptions, args.creativesPerPainPoint, LIMIT.description, "description", "Shop now"),
      },
    };
  });
}

