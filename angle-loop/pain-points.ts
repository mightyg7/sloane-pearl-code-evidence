/**
 * ABO pain-point generation — Furkan's pain-point marketing method.
 *
 * Encodes the same method the Mode-C dress pipeline uses
 * (src/lib/ugc-pipeline/dress-angles.ts), adapted for ABO STATIC ads:
 * for each angle, picture ONE specific sub-buyer, pick the ONE small
 * problem that feels HUGE to them, then earn the claim with a believable
 * MECHANISM grounded in what's VISIBLE in the product photos (never an
 * unverifiable internal feature). Each angle becomes one ad set; you only
 * need one to hit.
 *
 * Differs from dress-angles: static image (not video VO), so each angle
 * also yields a short punchy ON-IMAGE TEXT (the "P4IN"/"FOOTPAIN" trick)
 * and Meta-sized copy. Product photos are fed as vision blocks so the
 * mechanism + image prompt are grounded in the real garment.
 *
 * Uses ANTHROPIC_API_KEY_ADS (isolated ads budget), like translate.ts.
 */

import type Anthropic from "@anthropic-ai/sdk";
import { createAnthropic } from "@/lib/anthropic-factory";
import { trackAnthropicUsage } from "@/lib/usage-tracker";
import { getCurrentBrief, buildAngleBriefPromptBlock } from "@/lib/angle-loop/select";
import { EXPLORATION_FLOOR } from "@/lib/angle-loop/types";

const MODEL = "claude-sonnet-4-6";
// Each attempt is cheap on the happy path (~1.5k output tokens), so 4 is
// insurance against the provider proxy's intermittent mid-output stop
// (documented below on the JSON call) and against short-count under-delivery.
// Bounded by RETRY_BUDGET_MS below so a persistently-truncating model can't
// ride the retry loop past the route's own time budget.
const MAX_ATTEMPTS = 4;
// Ceiling, not a charge — ON THE HAPPY PATH, where billing (and latency) is
// on tokens actually produced. But when stop_reason === "max_tokens" persists
// across retries, the model genuinely produces up to this ceiling on EVERY
// attempt, so BOTH cost and latency scale with the cap — that is precisely
// the failure mode this hardening targets, so it can't be waved away as
// "free". A 3-angle x 3-creative response measures ~1540 output tokens; a
// 5-angle run at the same density is roughly 2500. 4000 keeps comfortable
// headroom for both while capping a single maxed-out attempt at ~96 tok/s
// (measured) to ~42s. The original 2600 was genuinely too tight for a
// 5-angle run; an earlier pass at 8000 overshot it the other way — a single
// maxed-out attempt there costs ~83s, so two of them alone (~166s) exceed
// the route's own `maxDuration = 120` before the vision pass or the route's
// subsequent generateHikePrimaries call even run. See RETRY_BUDGET_MS below,
// which is the actual backstop against that; this cap just keeps any one
// attempt individually affordable.
const JSON_MAX_TOKENS = 4000;
// Wall-clock ceiling on the JSON-generation retry loop below, checked before
// starting attempt 2+ (never before attempt 1) — it can only stop a NEW
// attempt from starting, it can't preempt one already in flight. So the true
// worst case is this budget PLUS one full further attempt, and that sum must
// stay under the route's `maxDuration = 120` alongside what runs after this
// loop returns:
//   RETRY_BUDGET_MS (55s) + one maxed-out attempt (~42s at JSON_MAX_TOKENS=
//   4000, ~96 tok/s) + the route's post-loop generateHikePrimaries call
//   (~14s) ≈ 111s — comfortably inside 120s.
// If either JSON_MAX_TOKENS or this budget changes, redo that arithmetic
// before picking a new value; that's the invariant this constant protects.
// In practice the failures we've actually observed are FAST ones (the model
// stopping early at ~339-416 tokens, ~4s each), so 55s still leaves room for
// several retries in the real-world case — this only trims the slow
// pathological path, which is exactly the one that would otherwise blow the
// route's budget.
const RETRY_BUDGET_MS = 55_000;

// Meta RECOMMENDED (delivery-quality) limits — NOT API hard caps. The
// API accepts longer, but Feed placements truncate past these, so we
// constrain the prompt and defensively clamp the output.
const LIMIT = { primary: 125, headline: 40, description: 30 } as const;

export interface PainPointCopy {
  primaryTexts: string[];
  headlines: string[];
  descriptions: string[];
  /** Hike-style archetype primaries (exactly 3) applied to EVERY ad of the
   *  ad set as Meta multiple-text options. Generated by
   *  hike-copy/generate.ts at preview time; legacy runs lack it. */
  primaryOptions?: string[];
  /** Hike-style register headlines (exactly 3), index-paired to
   *  primaryOptions. Same lifecycle: preview-generated, legacy runs lack it. */
  headlineOptions?: string[];
}

export interface PainPoint {
  slug: string;
  label: string;
  /** The SPECIFIC sub-buyer this angle pictures (Furkan's "close your eyes
   *  and see her"). Preview-only; not sent to Meta. Optional so the launch
   *  path + minimal test fixtures don't need to supply it. */
  buyer?: string;
  /** The ONE small problem that feels HUGE to that buyer. */
  painPoint?: string;
  /** The visible, believable reason the product fixes it — grounded in the
   *  product photo, never an unverifiable internal feature. */
  mechanism?: string;
  /** Short, punchy on-image text (3-8 chars, e.g. "P4IN"). Rendered onto
   *  the AtlasCloud creative. */
  onImageText?: string;
  /** AtlasCloud image prompt (square, no faces, white bg, on-image text). */
  imagePrompt: string;
  /** Collection runs only: 0-based index into the product set (matches
   *  scrapedProducts order) of the garment that best expresses this angle.
   *  Absent on single-product runs or when the model's pick was invalid. */
  productIndex?: number;
  productTitle?: string;
  /** That product's reference photo — grounds this angle's ad-set creatives. */
  productImageUrl?: string;
  copy: PainPointCopy;
}

/** One product in the pain-point grounding set (1 = single-product run,
 *  2-4 = collection run's top best-sellers, scrape order). */
export interface AboProductInput {
  title: string;
  description?: string;
  /** Public https photo URLs of THIS product; [0] is the creative reference. */
  imageUrls: string[];
}

export interface GeneratePainPointsArgs {
  /** Legacy single-product input. Ignored when `products` is present. */
  product?: { title: string; description?: string };
  /** Collection-aware input: 1-4 products (top best-sellers, scrape order).
   *  When >1, angles are collection-level and each is tagged with the
   *  product that best expresses it. */
  products?: AboProductInput[];
  collection?: string;
  /** Public product photo URLs — fed to Claude vision so the mechanism +
   *  image prompt are grounded in the real product (Furkan's "believable
   *  reason you can SEE"). Optional; falls back to text-only. Ignored when
   *  `products` is present (each product carries its own imageUrls). */
  productImageUrls?: string[];
  /** Brand name — referenced at most once; premium brands are NEVER named
   *  ("like a luxury brand, without saying which"). */
  brandName?: string;
  /** Number of pain points / ad sets to generate (caller already clamped 1-5). */
  count: number;
  /** Number of single ads per ad set — sizes each copy array (2-3). */
  creativesPerPainPoint: number;
  /** Meta ad-account id — scopes the Angle Brief lookup. Optional; falls
   *  back to META_AD_ACCOUNT_ID inside getCurrentBrief. */
  accountId?: string;
}

function normalizeProducts(args: GeneratePainPointsArgs): AboProductInput[] {
  if (args.products && args.products.length > 0) {
    return args.products
      .filter((p) => typeof p.title === "string" && p.title.trim().length > 0)
      .slice(0, 4)
      .map((p) => ({
        title: p.title.trim(),
        description: p.description,
        imageUrls: (p.imageUrls ?? []).filter((u) => /^https:\/\//i.test(u)).slice(0, 4),
      }));
  }
  if (!args.product?.title) {
    throw new Error("pain-points: either `products` or `product` is required");
  }
  return [
    {
      title: args.product.title,
      description: args.product.description,
      imageUrls: (args.productImageUrls ?? []).filter((u) => /^https:\/\//i.test(u)).slice(0, 4),
    },
  ];
}

export function slugify(label: string): string {
  return (
    label
      .toLowerCase()
      .replace(/[^a-z0-9]+/g, "-")
      .replace(/^-+|-+$/g, "")
      .slice(0, 40) || "pain"
  );
}

/** Truncate at a word boundary when over `max`, logging the cut. */
export function clampCopyField(text: string, max: number, field: string): string {
  const t = (text ?? "").trim();
  if (t.length <= max) return t;
  const cut = t.slice(0, max);
  const atBoundary = cut.replace(/\s+\S*$/, "").trim() || cut.trim();
  console.warn(
    `[abo:pain-points] ${field} over ${max} chars, truncated: "${t.slice(0, 60)}…"`,
  );
  return atBoundary;
}

/** Coerce a model copy array to exactly `n` entries, padding from the
 *  first entry (or `fallback`) and clamping each to `max`. */
function sizeAndClamp(
  arr: unknown,
  n: number,
  max: number,
  field: string,
  fallback: string,
): string[] {
  const list = Array.isArray(arr)
    ? arr.filter((s): s is string => typeof s === "string" && s.trim().length > 0)
    : [];
  const out: string[] = [];
  for (let i = 0; i < n; i++) {
    out.push(clampCopyField(list[i] ?? list[0] ?? fallback, max, field));
  }
  return out;
}

